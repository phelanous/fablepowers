#!/usr/bin/env bash
# Generates the Pi wrapper skills pi/skills/fablepowers-<x>/SKILL.md from skills/.
#
# One wrapper per skills/<x>/SKILL.md, except user-only skills (frontmatter
# `disable-model-invocation: true`: approve, withdraw), which Pi gets as the
# extension's /fablepowers:approve and /fablepowers:withdraw commands. A wrapper
# keeps the original description and points at the original SKILL.md by a path
# relative to the wrapper (../../../skills/<x>/SKILL.md).
#
# Usage: scripts/gen-pi-skills.sh [out-dir]   (default: <repo>/pi/skills)
# Existing fablepowers-* wrappers in out-dir are replaced; tests/pi compares the
# output with the committed files (drift test).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${1:-$ROOT/pi/skills}"
mkdir -p "$OUT"
rm -rf "$OUT"/fablepowers-*

# frontmatter <file>: the lines between the opening and closing `---`.
frontmatter() {
  awk 'NR == 1 { if ($0 != "---") exit; next } $0 == "---" { exit } { print }' "$1"
}

for skill in "$ROOT"/skills/*/SKILL.md; do
  name="$(basename "$(dirname "$skill")")"
  fm="$(frontmatter "$skill")"
  if grep -qx 'disable-model-invocation: true' <<<"$fm"; then
    continue
  fi
  desc="$(grep -m1 '^description: ' <<<"$fm" | sed 's/^description: //')" || true
  if [[ -z "$desc" ]]; then
    echo "gen-pi-skills: $skill has no one-line description" >&2
    exit 1
  fi
  mkdir -p "$OUT/fablepowers-$name"
  cat > "$OUT/fablepowers-$name/SKILL.md" <<EOF
---
name: fablepowers-$name
description: $desc
---

<!-- Generated by scripts/gen-pi-skills.sh from skills/$name/SKILL.md. Do not edit; rerun the script. -->

# fablepowers:$name on Pi

This Pi skill is the fablepowers skill \`fablepowers:$name\`. Read \`../../../skills/$name/SKILL.md\` (the path is relative to this file; it is \`<plugin root>/skills/$name/SKILL.md\`, and the fablepowers bootstrap gives the plugin root) and follow it.

Relative paths inside that file resolve against its own directory, \`../../../skills/$name/\`. Where it names a skill \`fablepowers:<x>\`, use the Pi skill \`fablepowers-<x>\`.
EOF
done
